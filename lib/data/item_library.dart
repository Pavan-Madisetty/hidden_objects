import '../models/world_def.dart';

/// Big pool of everyday objects. Every level picks its objects from the pool
/// of its world (plus general items), so the things you look for keep
/// changing from level to level. Append only: ids are position based.
class ItemLibrary {
  static final List<ItemDef> all = _build();
  static final Map<String, ItemDef> _byId = {for (final i in all) i.id: i};

  static ItemDef? byId(String id) => _byId[id];

  static const Map<String, List<String>> _worldCats = {
    'bedroom': ['toys', 'clothes', 'household', 'music', 'food'],
    'kitchen': ['food', 'kitchen', 'household', 'farm'],
    'school': ['school', 'sports', 'music', 'tech', 'toys'],
    'playground': ['sports', 'toys', 'nature', 'vehicles', 'food'],
    'farm': ['farm', 'food', 'nature', 'tools', 'animals'],
    'zoo': ['animals', 'nature', 'food', 'toys'],
    'pirate': ['sea', 'treasure', 'tools', 'vehicles', 'animals'],
    'forest': ['nature', 'animals', 'fantasy', 'food'],
    'space': ['space', 'tech', 'fantasy', 'tools'],
    'castle': ['fantasy', 'treasure', 'music', 'clothes', 'household'],
  };

  static final Map<String, List<ItemDef>> _cache = {};

  /// Objects that belong in [worldId] (themed categories first).
  static List<ItemDef> forWorld(String worldId) {
    return _cache.putIfAbsent(worldId, () {
      final cats = _worldCats[worldId] ?? const <String>['toys', 'food', 'household'];
      return [for (final i in all) if (cats.any((c) => i.id.startsWith('${c}_'))) i];
    });
  }

  static List<ItemDef> _build() {
    final out = <ItemDef>[];
    _data.forEach((cat, list) {
      for (var i = 0; i < list.length; i++) {
        out.add(ItemDef('${cat}_$i', list[i][0], list[i][1]));
      }
    });
    return out;
  }
}

